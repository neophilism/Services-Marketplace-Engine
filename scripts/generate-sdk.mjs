import assert from 'node:assert/strict';
import fs from 'node:fs';

const specPath = new URL('../contracts/openapi.json', import.meta.url);
const outputPath = new URL('../packages/sdk/src/index.ts', import.meta.url);
const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));

assert.equal(spec.openapi, '3.1.0');
const operation = spec.paths?.['/v1/organizations/{organizationId}/resources/{resourceId}']?.get;
assert.equal(operation?.operationId, 'getResource');
assert.deepEqual(operation.security, [{bearerAuth: []}]);
assert.ok(operation.responses?.['200']);
assert.ok(operation.responses?.['400']);
assert.ok(operation.responses?.['403']);
assert.equal(spec.components?.parameters?.ContractVersion?.schema?.const, 1);
assert.equal(spec.components?.schemas?.AuthorizationDenied?.properties?.code?.const, 'authorization_denied');

const generated = `// Generated by scripts/generate-sdk.mjs from contracts/openapi.json. Do not edit.
export const CONTRACT_VERSION = ${spec.components.parameters.ContractVersion.schema.const} as const;

export interface Resource {
  readonly id: string;
  readonly organizationId: string;
}

export type ApiErrorCode = 'unsupported_contract_version' | 'authorization_denied' | 'unexpected_response';

export class ApiError extends Error {
  readonly status: number;
  readonly code: ApiErrorCode;

  constructor(status: number, code: ApiErrorCode) {
    super(code);
    this.name = 'ApiError';
    this.status = status;
    this.code = code;
  }
}

export interface FetchResponse {
  readonly ok: boolean;
  readonly status: number;
  json(): Promise<unknown>;
}

export type FetchLike = (
  input: string,
  init: {readonly method: 'GET'; readonly headers: Readonly<Record<string, string>>},
) => Promise<FetchResponse>;

export interface ClientOptions {
  readonly baseUrl: string;
  readonly bearerToken: string;
  readonly fetch: FetchLike;
}

function requiredSegment(name: string, value: string): string {
  if (value.length === 0) throw new TypeError(name + ' is required');
  return encodeURIComponent(value);
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

export function createClient(options: ClientOptions) {
  if (!/^https:\\/\\//.test(options.baseUrl)) throw new TypeError('baseUrl must use HTTPS');
  if (options.bearerToken.length === 0) throw new TypeError('bearerToken is required');
  const baseUrl = options.baseUrl.replace(/\\/$/, '');

  return {
    async getResource(organizationId: string, resourceId: string): Promise<Resource> {
      const path = '/v1/organizations/' + requiredSegment('organizationId', organizationId)
        + '/resources/' + requiredSegment('resourceId', resourceId);
      const response = await options.fetch(baseUrl + path, {
        method: 'GET',
        headers: {
          accept: 'application/json',
          authorization: 'Bearer ' + options.bearerToken,
          'x-contract-version': String(CONTRACT_VERSION),
        },
      });
      const body: unknown = await response.json();
      if (!response.ok) {
        const code = isRecord(body) && (body.code === 'authorization_denied' || body.code === 'unsupported_contract_version')
          ? body.code
          : 'unexpected_response';
        throw new ApiError(response.status, code);
      }
      if (!isRecord(body) || typeof body.id !== 'string' || typeof body.organizationId !== 'string') {
        throw new ApiError(response.status, 'unexpected_response');
      }
      return {id: body.id, organizationId: body.organizationId};
    },
  };
}
`;

if (process.argv.includes('--check')) {
  assert.equal(fs.readFileSync(outputPath, 'utf8'), generated, 'generated SDK is stale; run npm run generate:sdk');
  console.log('Generated SDK matches contracts/openapi.json');
} else {
  fs.mkdirSync(new URL('../packages/sdk/src/', import.meta.url), {recursive: true});
  fs.writeFileSync(outputPath, generated);
}
